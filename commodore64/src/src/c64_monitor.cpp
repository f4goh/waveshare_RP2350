void c64_monitor_render(void)
{
    if (!s_monActive) return;

    // Fond bleu fonce (palette index 254 = 0x352879) et texte blanc (index 1)
    uint8_t *fb = g_pixels;
    for (int y = 0; y < 240; y++) {
        uint8_t *row = fb + (y + C64_CROP_TOP) * C64_DISPLAY_WIDTH + C64_CROP_LEFT;
        memset(row, 254, 320);
    }

    for (int y = 0; y < MON_LINES; y++) {
        int py = y * 10 + 2;
        for (int x = 0; x < MON_COLS; x++) {
            char ch = s_screenText[y][x];
            if (ch <= 32 || ch > 126) continue;
            const uint8_t *glyph = font_6x8[(unsigned char)ch - 32];
            int px = x * 8 + 4;
            for (int r = 0; r < 8; r++) {
                uint8_t bits = glyph[r];
                uint8_t *dst = fb + (py + r + C64_CROP_TOP) * C64_DISPLAY_WIDTH + px + C64_CROP_LEFT;
                for (int c = 0; c < 6; c++) {
                    if (bits & (0x80 >> c)) {
                        dst[c] = 1; // Blanc
                    }
                }
            }
        }
    }
}

void c64_monitor_key(uint8_t ascii)
{
    if (!s_monActive) return;
    if (ascii == 0x1B) { // ESC
        c64_monitor_close();
    } else if (ascii == '\r' || ascii == '\n') {
        s_uartLineBuf[s_uartLineIdx] = '\0';
        mon_printf("\n");
        exec_command(s_uartLineBuf);
        s_uartLineIdx = 0;
    } else if (ascii == 0x08 || ascii == 0x7F) {
        if (s_uartLineIdx > 0) {
            s_uartLineIdx--;
            int len = strlen(s_screenText[s_curLine]);
            if (len > 0) s_screenText[s_curLine][len - 1] = '\0';
        }
    } else if (s_uartLineIdx < (int)sizeof(s_uartLineBuf) - 1 && ascii >= 32 && ascii < 127) {
        s_uartLineBuf[s_uartLineIdx++] = (char)ascii;
        char temp[2] = { (char)ascii, '\0' };
        mon_print(temp);
    }
}
