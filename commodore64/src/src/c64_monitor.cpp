static bool s_monActive = false;
static char s_uartLineBuf[80];
static int  s_uartLineIdx = 0;

#define MON_LINES 24
#define MON_COLS  40
static char s_screenText[MON_LINES][MON_COLS + 1];
static int  s_curLine = 0;

static void mon_cls(void)
{
    for (int y = 0; y < MON_LINES; y++) {
        memset(s_screenText[y], ' ', MON_COLS);
        s_screenText[y][MON_COLS] = '\0';
    }
    s_curLine = 0;
}

static void mon_print(const char *str)
{
    while (*str) {
        if (*str == '\n') {
            s_curLine++;
            if (s_curLine >= MON_LINES) {
                for (int y = 1; y < MON_LINES; y++) {
                    memcpy(s_screenText[y - 1], s_screenText[y], MON_COLS + 1);
                }
                memset(s_screenText[MON_LINES - 1], ' ', MON_COLS);
                s_screenText[MON_LINES - 1][MON_COLS] = '\0';
                s_curLine = MON_LINES - 1;
            }
        } else if (*str >= 32 && *str < 127) {
            int len = strlen(s_screenText[s_curLine]);
            if (len < MON_COLS) {
                s_screenText[s_curLine][len] = *str;
                s_screenText[s_curLine][len + 1] = '\0';
            }
        }
        str++;
    }
}

static void mon_printf(const char *fmt, ...)
{
    char buf[128];
    va_list args;
    va_start(args, fmt);
    vsnprintf(buf, sizeof(buf), fmt, args);
    va_end(args);
    mon_print(buf);
    uart_puts(C64_UART_ID, buf);
}

void c64_monitor_init(void)
{
    uart_init(C64_UART_ID, C64_UART_BAUD);
    gpio_set_function(PIN_UART_TX, GPIO_FUNC_UART);
    gpio_set_function(PIN_UART_RX, GPIO_FUNC_UART);
    mon_cls();
    s_monActive = false;
    s_uartLineIdx = 0;
}

void c64_monitor_open(void)
{
    s_monActive = true;
    mon_cls();
    mon_printf("=== C64 MONITOR (RP2350) ===\n");
    mon_printf("COMMANDS: M <hex> (dump) | R (regs)\n");
    mon_printf("          W <addr> <val> | X (exit)\n");
    mon_printf("> ");
}

void c64_monitor_close(void)
{
    s_monActive = false;
}

bool c64_monitor_is_open(void)
{
    return s_monActive;
}

static void exec_command(char *cmd)
{
    while (*cmd == ' ') cmd++;
    if (*cmd == '\0') {
        mon_printf("> ");
        return;
    }

    char op = toupper((unsigned char)*cmd++);
    while (*cmd == ' ') cmd++;

    uint8_t *ram = c64_get_ram();

    if (op == 'X' || op == 'Q') {
        c64_monitor_close();
        return;
    } else if (op == 'M') {
        unsigned int addr = 0x0801;
        sscanf(cmd, "%x", &addr);
        addr &= 0xFFFF;
        if (ram) {
            for (int row = 0; row < 8; row++) {
                uint16_t a = (addr + row * 8) & 0xFFFF;
                mon_printf("%04X: ", a);
                for (int b = 0; b < 8; b++) {
                    mon_printf("%02X ", ram[(a + b) & 0xFFFF]);
                }
                mon_printf("| ");
                for (int b = 0; b < 8; b++) {
                    uint8_t ch = ram[(a + b) & 0xFFFF];
                    mon_printf("%c", (ch >= 32 && ch < 127) ? ch : '.');
                }
                mon_printf("\n");
            }
        }
    } else if (op == 'W') {
        unsigned int addr = 0, val = 0;
        if (sscanf(cmd, "%x %x", &addr, &val) == 2 && ram) {
            ram[addr & 0xFFFF] = (uint8_t)val;
            mon_printf("Wrote %02X to %04X\n", val & 0xFF, addr & 0xFFFF);
        } else {
            mon_printf("Syntax: W <addr> <val>\n");
        }
    } else if (op == 'R') {
        mon_printf("C64 RAM at %p\n", ram);
    } else {
        mon_printf("Unknown command. M, W, R, X\n");
    }
    mon_printf("> ");
}

void c64_monitor_uart_poll(void)
{
    while (uart_is_readable(C64_UART_ID)) {
        char c = (char)uart_getc(C64_UART_ID);
        if (c == '\r' || c == '\n') {
            uart_putc(C64_UART_ID, '\r');
            uart_putc(C64_UART_ID, '\n');
            s_uartLineBuf[s_uartLineIdx] = '\0';
            exec_command(s_uartLineBuf);
            s_uartLineIdx = 0;
        } else if (c == 0x08 || c == 0x7F) {
            if (s_uartLineIdx > 0) {
                s_uartLineIdx--;
                uart_puts(C64_UART_ID, "\b \b");
            }
        } else if (s_uartLineIdx < (int)sizeof(s_uartLineBuf) - 1 && c >= 32 && c < 127) {
            s_uartLineBuf[s_uartLineIdx++] = c;
            uart_putc(C64_UART_ID, c);
        }
    }
}

